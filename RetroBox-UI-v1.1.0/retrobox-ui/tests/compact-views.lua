return function(Mock,Library,test)
    local function fixture()
        local w=Library:CreateWindow({Id='compact-tests',Settings=false,FileStorage=false,ReducedMotion=true})
        local section=w:CreateTab({Title='Data'}):CreateSection('Views')
        return w,section
    end
    local function finish(w)
        w:Destroy(); Mock.pump(20)
        assert(Mock.Connections==0,'Leaked '..Mock.Connections..' connections')
        assert(next(w._icons)==nil and next(w.Tasks)==nil)
        assert((Mock.ParentLockErrors or 0)==0 and (Mock.DestroyedIconWrites or 0)==0)
    end
    test('HUD updates a shared State while the menu is hidden',function()
        local w=fixture(); local money=w:CreateState(1250)
        local hud=w:CreateHUD({Id='session',Title='Session',Position=Vector2.new(.8,.8)})
        local item=hud:AddValue({Id='money',Title='Money',State=money,Format='Compact',Unit='$',Icon='money'})
        assert(item.ValueLabel.Text=='1.2K $' or item.ValueLabel.Text=='1.3K $')
        w:Hide(); money:Set(2500); assert(hud.Frame.Visible and item:GetValue()==2500)
        w:Show(); assert(hud.Frame.Visible); hud:SetLayout({VisibleWithMenu=false}); assert(not hud.Frame.Visible)
        w:Hide(); assert(hud.Frame.Visible); finish(w)
    end)
    test('HUD bindings preserve false and nil transforms without callbacks',function()
        local w=fixture(); local state=w:CreateState(true); local hud=w:CreateHUD()
        local item=hud:AddValue({Id='boolean',State=state,Transform=function() return false end})
        assert(item:GetValue()==false)
        item:BindState(state,{Transform=function() return nil end}); assert(item:GetValue()==nil)
        item:Destroy(); state:Set(false); finish(w)
    end)
    test('HUD layout collapses, clamps mobile geometry and saves preferences',function()
        local w=fixture(); local hud=w:CreateHUD({Id='mobile',Width=300})
        for i=1,12 do hud:AddValue({Id='item-'..i,Value=i}) end
        hud:SetLayout({Position=Vector2.new(1,1),Orientation='Horizontal',Scale=1.5,Opacity=.6,Pinned=true})
        w.Root.AbsoluteSize=Vector2.new(320,480); w:_layoutFloating()
        local size=hud.Frame.Size; local pos=hud.Frame.Position
        assert(pos.X.Offset+size.X.Offset*hud.ActualScale<=312.001 and pos.Y.Offset+size.Y.Offset*hud.ActualScale<=472.001)
        hud:SetCollapsed(true); assert(hud.Frame.Size.Y.Offset==40 and not hud.Body.Visible and hud.TitleLabel.Text:find('1'))
        local layout=hud:GetLayout(); layout.Position.X=0; assert(hud.Position.X==1)
        local config=w:ExportConfig(true); hud:SetLayout({Visible=false,Collapsed=false,Opacity=1})
        assert(w:ImportConfig(config,{Silent=true})); assert(hud.Visible and hud.Collapsed and hud.Opacity==.6)
        finish(w)
    end)
    test('HUD rejects invalid layout atomically',function()
        local w=fixture(); local hud=w:CreateHUD(); local config=w:ExportConfig(true)
        config.Appearance.Advanced.CompactViews['HUD/hud'].Opacity=2
        config.Appearance.Theme='Hacker'; assert(not w:ImportConfig(config)); assert(w.Theme=='Retro98' and hud.Opacity==.95)
        assert(not pcall(hud.SetLayout,hud,{Visible=false,Width=0})); assert(hud.Visible)
        finish(w)
    end)
    test('pinning tracks silent values and never repeats the source callback',function()
        local w,s=fixture(); local count=0; local card=s:AddStatCard({Id='money',Title='Money',Value=10,Format='Compact',Callback=function() count=count+1 end,Pinnable=true})
        card.PinButton.Activated:Fire(); local hud=w:GetHUD('pinned'); local item=card._hudPins[hud]
        assert(item and card.PinButton.Text=='Soltar')
        card:SetValue(5000,true); assert(item:GetValue()==5000 and count==0)
        assert(card:PinToHUD(hud)==item); card:SetValue(6000); Mock.pump(); assert(count==1 and item:GetValue()==6000)
        card:SetTitle('Coins'); assert(item.Title=='Coins')
        card.PinButton.Activated:Fire(); assert(item.Destroyed and not next(card._hudPins)); finish(w)
    end)
    test('progress and label pins share values and destroy with their source',function()
        local w,s=fixture(); local hud=w:CreateHUD()
        local progress=s:AddProgress({Id='progress',Min=10,Max=20,Default=10}); local label=s:AddLabel({Id='label',Title='Ready'})
        local p=progress:PinToHUD(hud); local l=label:PinToHUD(hud)
        progress:SetValue(15,true); label:SetText('Working'); assert(p.Fill.Size.X.Scale==.5 and l:GetValue()=='Working')
        progress:Destroy(); assert(p.Destroyed); label:Destroy(); assert(l.Destroyed and #hud.Items==0); finish(w)
    end)
    test('pin membership restores with late HUD and control construction',function()
        local w,s=fixture(); local card=s:AddStatCard({Id='card',Value=4}); local hud=w:CreateHUD({Id='late'})
        card:PinToHUD(hud,{Id='pinned-card'}); hud:SetVisible(false); local config=w:ExportConfig()
        finish(w)
        w,s=fixture(); assert(w:ImportConfig(config,{Silent=true}))
        hud=w:CreateHUD({Id='late'}); assert(not hud.Visible and not hud._items['pinned-card'])
        card=s:AddStatCard({Id='card',Value=8}); assert(hud._items['pinned-card']:GetValue()==8)
        finish(w)
    end)
    test('timers use the existing scheduler and stop on pause or destroy',function()
        local w=fixture(); local hud=w:CreateHUD(); local timer=hud:AddTimer({Id='clock',Start=true})
        local connection=w._runtimeConnection; Mock.Time=Mock.Time+2; Mock.Services.RunService.RenderStepped:Fire(.1); Mock.pump()
        assert(timer:GetValue()>=2 and timer.ValueLabel.Text=='00:02' and w._runtimeConnection==connection)
        timer:Pause(); assert(w._runtimeConnection==nil); timer:Reset(60); assert(timer.ValueLabel.Text=='01:00')
        timer:Start(); timer:Destroy(); assert(next(w.Tasks)==nil and w._runtimeConnection==nil); finish(w)
    end)
    test('HUD observes tasks without starting or changing their interval',function()
        local w=fixture(); local hud=w:CreateHUD(); local calls=0
        local job=w:CreateTask({Id='job',Interval=1,Callback=function() calls=calls+1 end})
        local item=hud:AddTask({Id='status',Task=job}); assert(item:GetValue()=='Inactive' and calls==0 and not job.Requested)
        job:Start(); assert(item:GetValue()=='Waiting'); job:Stop(); assert(item:GetValue()=='Stopped' and job.Interval==1)
        finish(w)
    end)
    test('compact actions reuse floating Toggle, Button and Hold semantics',function()
        local w,s=fixture(); local count=0
        local toggle=s:AddToggle({Id='toggle'}); local press=s:AddButton({Id='press',Callback=function() count=count+1 end})
        local hold=s:AddKeybind({Id='hold',Mode='Hold',Callback=function(active) count=count+(active and 10 or 100) end})
        local bar=w:CreateActionBar({Id='bar'}); local a=bar:AddAction({Control=toggle}); local b=bar:AddAction({Control=press}); local c=bar:AddAction({Control=hold})
        assert(not toggle:GetValue()); a.Button.Activated:Fire(); b.Button.Activated:Fire(); Mock.pump(); assert(toggle:GetValue() and count==1)
        local input={UserInputType=Enum.UserInputType.Touch,Position=Vector2.new(10,10)}
        c.Button.InputBegan:Fire(input); Mock.pump(); assert(hold.Active and count==11)
        Mock.Services.UserInputService.WindowFocusReleased:Fire(); Mock.pump(); assert(not hold.Active and count==111)
        bar:SetCollapsed(true); assert(not bar.Body.Visible); bar:SetCollapsed(false)
        toggle:SetDisabled(true); a.Button.Activated:Fire(); assert(toggle:GetValue())
        press:Destroy(); assert(b.Destroyed and #bar.Items==2)
        finish(w)
    end)
    test('compact view reset uses constructor preferences',function()
        local w=fixture(); local hud=w:CreateHUD({Position=Vector2.new(.1,.2),Opacity=.8})
        hud:SetLayout({Position=Vector2.new(.9,.9),Opacity=.3,Collapsed=true}); w:Reset(true)
        assert(hud.Position.X==.1 and hud.Opacity==.8 and not hud.Collapsed); finish(w)
    end)
    for _,deferred in ipairs({false,true}) do
        test('compact lifecycle '..(deferred and 'deferred' or 'immediate')..' handles replacement and parent destruction',function()
            Mock.StrictIconLifecycle=true; Mock.DeferDestroying=deferred; Mock.ParentLockErrors=0; Mock.DestroyedIconWrites=0
            local w,s=fixture(); local hud=w:CreateHUD(); local item=hud:AddValue({Id='icon',Value=3,Icon='diamond'})
            local bar=w:CreateActionBar(); local floating=bar:AddAction({Id='action',Callback=function() end})
            hud.Frame:Destroy(); bar.Frame:Destroy(); item:SetValue(4); Mock.pump()
            hud:Destroy(); item:Destroy(); bar:Destroy(); floating:Destroy(); finish(w)
            w,s=fixture(); hud=w:CreateHUD(); hud:AddValue({Value=8,Icon='tools'})
            local replacement=fixture(); assert(w.Destroyed and hud.Destroyed); finish(replacement)
            Mock.DeferDestroying=false; Mock.StrictIconLifecycle=false
        end)
    end
    test('pin options, help badges and repeated pin availability do not overlap or leak',function()
        local w,s=fixture(); local progress=s:AddProgress({Id='p',Tooltip='Help',Pinnable=true})
        local baseline=Mock.Connections
        for i=1,10 do progress:SetPinnable(false); progress:SetPinnable(true) end
        assert(Mock.Connections==baseline)
        assert(progress.PinButton.Position.X.Offset+progress.PinButton.Size.X.Offset<=progress.InfoButton.Position.X.Offset)
        local hud=w:CreateHUD(); local pin=progress:PinToHUD(hud,{Title='Custom',Unit='pts'})
        progress:SetTitle('Changed'); progress:SetIcon('diamond'); assert(pin.Title=='Custom' and pin.Unit=='pts' and pin._icon.Frame:GetAttribute('RetroBoxIcon')=='diamond')
        finish(w)
    end)
    test('oversized pin imports fail before changing theme or HUD visibility',function()
        local w,s=fixture(); local hud=w:CreateHUD(); for i=1,32 do hud:AddValue({Id='v'..i,Value=i}) end
        s:AddStatCard({Id='card',Value=1}); local config=w:ExportConfig(true)
        config.Appearance.Theme='Hacker'; local layout=config.Appearance.Advanced.CompactViews['HUD/hud']; layout.Visible=false; layout.Pins={card={Id='pin'}}
        assert(not w:ImportConfig(config)); assert(w.Theme=='Retro98' and hud.Visible and #hud.Items==32)
        finish(w)
    end)
    test('HUD idle rendering adds no frame loop and touch dragging respects locks',function()
        local w=fixture(); local hud=w:CreateHUD(); hud:AddValue({Value=3})
        assert(w._runtimeConnection==nil)
        local header=hud.TitleLabel.Parent
        local input={UserInputType=Enum.UserInputType.Touch,Position=Vector2.new(30,80)}
        header.InputBegan:Fire(input); assert(w._drag and w._drag.Owner==hud)
        w._drag.Update(Vector2.new(90,140)); w:_endDrag(); assert(hud.Position.X>0)
        hud:SetPinned(true); header.InputBegan:Fire(input); assert(not w._drag)
        finish(w)
    end)
    test('widget initial false, numeric formatters and generated IDs survive replacements',function()
        local w=fixture(); local hud=w:CreateHUD()
        assert(hud:AddValue({Id='boolean',Value=false}):GetValue()==false)
        local calls=0; local item=hud:AddValue({Id='formatted',Value=20,Format=function(value) assert(type(value)=='number'); calls=calls+1; return value..' points' end})
        assert(item.ValueLabel.Text=='20 points' and calls==1)
        local first=hud:AddValue({Value=1}); local second=hud:AddValue({Value=2}); first:Destroy()
        assert(hud:AddValue({Value=3}).Id~=second.Id)
        local count=#hud.Items
        assert(not pcall(hud.AddProgress,hud,{Value='bad'}) and #hud.Items==count)
        assert(not pcall(hud.AddValue,hud,{Value={}}) and #hud.Items==count)
        finish(w)
    end)
    test('HUD themes, custom icons and PixelIcons toggles preserve cleanup',function()
        local w=fixture(); local hud=w:CreateHUD(); local item=hud:AddValue({Id='money',Value=50,Icon='money'})
        for _,name in ipairs(Library:GetThemeNames()) do w:SetTheme(name) end
        for i=1,8 do item:SetIcon('tools'); w:SetPixelIcons(false); w:SetPixelIcons(true); item:SetIcon('diamond') end
        assert(item._icon.Frame:GetAttribute('RetroBoxIcon')=='diamond'); finish(w)
    end)
end
