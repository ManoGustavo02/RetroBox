return function(Mock,Library,test)
    local function fixture() return Library:CreateWindow({Id='session-test',FileStorage=false,Settings=false,ReducedMotion=true}) end
    local function finish(w) w:Destroy(); Mock.pump(100); Mock.Warnings={}; assert(Mock.Connections==0) end
    test('session captures only registered states and snapshot data does not alias live values',function()
        local w=fixture(); local state=w:CreateState({Count=3}); w:CreateState('unregistered')
        w:RegisterSessionState('count',state); local snap=assert(w:CreateSessionSnapshot())
        assert(snap.States.count.Value.Count==3 and snap.States.unregistered==nil)
        snap.States.count.Value.Count=99; assert(state:Get().Count==3); finish(w)
    end)
    test('session restores values through bindings without firing control callbacks or persisting a profile',function()
        local w=fixture(); local state=w:CreateState(5); w:RegisterSessionState('count',state)
        local section=w:CreateTab('Tab'):CreateSection('Section'); local calls=0
        local slider=section:AddSlider({Id='slider',Min=0,Max=100,Default=0,Callback=function() calls=calls+1 end})
        slider:BindState(state,{FireCallback=true}); Mock.pump(); calls=0
        local snap=assert(w:CreateSessionSnapshot()); state:Set(9); Mock.pump(); calls=0
        assert(w:RestoreSessionSnapshot(snap)); Mock.pump()
        assert(state:Get()==5 and slider:GetValue()==5 and calls==0)
        assert(not w:ExportConfig():find('RetroBoxSession',1,true)); finish(w)
    end)
    test('session restoration reports missing and unknown registered keys',function()
        local w=fixture(); local first=w:CreateState(nil); local second=w:CreateState(2)
        w:RegisterSessionState('first',first); local snap=assert(w:CreateSessionSnapshot())
        w:UnregisterSessionState('first'); w:RegisterSessionState('second',second)
        local ok,report=w:RestoreSessionSnapshot(snap); assert(ok and report.Restored==0 and report.Unknown[1]=='first' and report.Missing[1]=='second'); finish(w)
    end)
    test('session rejects functions Instances threads and scopes instead of serializing runtime resources',function()
        local w=fixture(); local object=Instance.new('Frame'); w:Manage(object)
        for _,value in ipairs({function() end,object,coroutine.create(function() end),w:CreateScope()}) do
            local ok,state=pcall(w.CreateState,w,value)
            if ok then w:RegisterSessionState('bad',state); assert(not w:CreateSessionSnapshot()) end
        end
        finish(w)
    end)
    test('session rejects cyclic oversized and incompatible snapshots before changing valid states',function()
        local w=fixture(); local state=w:CreateState(5); w:RegisterSessionState('count',state)
        local snap=assert(w:CreateSessionSnapshot()); snap.SchemaVersion=2; assert(not w:RestoreSessionSnapshot(snap))
        snap.SchemaVersion=1; snap.States.count.Value=0/0; assert(not w:RestoreSessionSnapshot(snap))
        snap.States.count.Value={}; snap.States.count.Value.self=snap.States.count.Value; assert(not w:RestoreSessionSnapshot(snap))
        snap.States.count.Value=('x'):rep(262145); assert(not w:RestoreSessionSnapshot(snap))
        assert(state:Get()==5); finish(w)
    end)
    test('session validates every registered value before applying the snapshot',function()
        local w=fixture(); local a=w:CreateState(1); local b=w:CreateState(2,{Validate=function(v) return type(v)=='number' and v>=0,'positive required' end})
        w:RegisterSessionState('a',a); w:RegisterSessionState('b',b)
        local snap=assert(w:CreateSessionSnapshot()); snap.States.a.Value=10; snap.States.b.Value=-1
        assert(not w:RestoreSessionSnapshot(snap)); assert(a:Get()==1 and b:Get()==2); finish(w)
    end)
    test('session reexecution restores transient counters into new states with the same stable window Id',function()
        local w=fixture(); local count=w:CreateState(17); w:RegisterSessionState('count',count)
        local snap=assert(w:CreateSessionSnapshot()); w:Destroy(); assert(w._sessionStates==nil)
        local fresh=fixture(); local nextCount=fresh:CreateState(0); fresh:RegisterSessionState('count',nextCount)
        assert(fresh:RestoreSessionSnapshot(snap) and nextCount:Get()==17 and count.Destroyed); finish(fresh)
    end)
    test('session registration rejects other-window and computed states and releases external references',function()
        local w=fixture(); local external=Library:CreateState(4); w:RegisterSessionState('external',external)
        local computed=w:Computed({external},function(v) return v*2 end)
        assert(not pcall(w.RegisterSessionState,w,'computed',computed))
        assert(not pcall(w.RegisterSessionState,w,'bad key',external)); finish(w)
        assert(not external.Destroyed and next(external._listeners)==nil); external:Destroy()
        assert(not w:CreateSessionSnapshot() and not w:RestoreSessionSnapshot({}))
    end)
    test('integration checks capabilities before creating a window and preserves CallbackExecutor arguments',function()
        local previous=loadstring; loadstring=nil
        local missing=Library:CreateIntegration({Required={'loadstring'}})
        assert(not missing and next(Library.Windows)==nil)
        local executions=0
        local helper=assert(Library:CreateIntegration({Window={Id='helper',FileStorage=false,Settings=false},CallbackExecutor=function(callback,args)
            executions=executions+1; return callback(table.unpack(args,1,args.n))
        end}))
        local ok,result=helper:Run(function(a,b) return a+b end,2,3)
        assert(ok and result==5 and executions==1 and helper.Capabilities.loadstring==false); finish(helper.Window); assert(helper.Destroyed)
        loadstring=previous
    end)
    test('integration initialization and scoped resources clean exactly once on external destruction',function()
        local cleaned=0
        local helper=assert(Library:CreateIntegration({Window={Id='helper',FileStorage=false,Settings=false},Initialize=function(owner)
            owner:Manage(function() cleaned=cleaned+1 end)
            owner.Window:CreateTab('Main'):CreateSection('Section'):AddLabel({Title='Initialized'})
        end}))
        finish(helper.Window); helper:Destroy(); assert(cleaned==1 and helper.Destroyed and not helper:Run(function() end))
    end)
    test('integration reports initialization failure and leaves no orphan window or scope',function()
        local cleaned,errors=0,0
        local helper,reason=Library:CreateIntegration({Window={Id='helper',FileStorage=false,Settings=false,ErrorNotifications=false},OnError=function() errors=errors+1 end,Initialize=function(owner)
            owner:Manage(function() cleaned=cleaned+1 end); error('initialization failed')
        end})
        Mock.pump(100); assert(not helper and reason:find('initialization failed',1,true) and cleaned==1 and errors==1)
        assert(Mock.Connections==0 and next(Library.Windows)==nil); Mock.Warnings={}
    end)
end
