-- Identity comes from LocalPlayer properties, independently of HTTP/avatar work.
return function(Mock,Library,test)
    local players=Mock.Services.Players; local original=players.LocalPlayer;local thumbnail=players.GetUserThumbnailAsync
    local sequence=0
    local function player(name,display,id)
        local p=Instance.new('Player');p.Name=name;p.DisplayName=display;p.UserId=id or 100
        return p
    end
    local function fixture()
        sequence=sequence+1;Library._thumbnails={};Mock.Warnings={}
        return Library:CreateWindow({Id='identity-'..sequence,Parent=original:FindFirstChild('PlayerGui'),Settings=false,FileStorage=false,ReducedMotion=true,Locale='pt-BR'})
    end
    local function finish(w)
        w:Destroy();players.LocalPlayer=original;players.GetUserThumbnailAsync=thumbnail
        Mock.pump(100);Mock.YieldingTasks=false;Library._thumbnails={}
        assert(Mock.Connections==0,'Profile connections leaked')
        assert(#Mock.Warnings==0,table.concat(Mock.Warnings,'\n'))
    end
    test('profile binds when LocalPlayer arrives after GUI creation',function()
        players.LocalPlayer=nil;local w=fixture()
        assert(w.DisplayNameLabel.Text~='Player' and w.UsernameLabel.Text~='@player')
        local p=player('Gustavo_2133','Mano Gustavo');players.LocalPlayer=p;Mock.pump()
        assert(w.DisplayNameLabel.Text=='Mano Gustavo' and w.UsernameLabel.Text=='@Gustavo_2133')
        finish(w)
    end)
    test('late name display name and user id populate without recreating the window',function()
        local p=player('','',0);players.LocalPlayer=p;local w=fixture()
        p.Name='RealUser';assert(w.UsernameLabel.Text=='@RealUser' and w.DisplayNameLabel.Text=='RealUser')
        p.DisplayName='Nome real';p.UserId=101;Mock.pump()
        assert(w.DisplayNameLabel.Text=='Nome real' and w.Avatar.Image~='')
        finish(w)
    end)
    test('username changes are observed separately from DisplayName',function()
        local p=player('before','Display');players.LocalPlayer=p;local w=fixture()
        p.Name='after';assert(w.UsernameLabel.Text=='@after' and w.DisplayNameLabel.Text=='Display')
        p.DisplayName='Changed';assert(w.DisplayNameLabel.Text=='Changed');finish(w)
    end)
    test('PlayerAdded never adopts a different player as the local identity',function()
        players.LocalPlayer=nil;local w=fixture();players.PlayerAdded:Fire(player('Stranger','Other'))
        assert(w.DisplayNameLabel.Text~='Other' and w.UsernameLabel.Text~='@Stranger')
        local p=player('Me','My display');players.LocalPlayer=p;players.PlayerAdded:Fire(p)
        assert(w.DisplayNameLabel.Text=='My display' and w.UsernameLabel.Text=='@Me');finish(w)
    end)
    test('avatar failures do not replace verified profile text',function()
        players.LocalPlayer=player('Verified','Actual display')
        players.GetUserThumbnailAsync=function() error('Avatar offline') end
        local w=fixture();Mock.pump(10)
        assert(w.DisplayNameLabel.Text=='Actual display' and w.UsernameLabel.Text=='@Verified')
        w:Hide();w:Show();assert(w.UsernameLabel.Text=='@Verified');finish(w)
    end)
    test('late avatar response for an old identity cannot overwrite a new profile',function()
        Mock.YieldingTasks=true
        players.LocalPlayer=player('First','First display',200)
        players.GetUserThumbnailAsync=function(_,id) task.wait(2);return 'avatar/'..id,true end
        local w=fixture();Mock.pump()
        players.LocalPlayer=player('Second','Second display',201);Mock.pump();Mock.pump(3)
        assert(w.UsernameLabel.Text=='@Second' and w.Avatar.Image=='avatar/201')
        finish(w)
    end)
    test('reopening refreshes identity even if the executor dropped an event',function()
        local p=player('Before','Original');players.LocalPlayer=p;local w=fixture()
        w:Hide();p._props.Name='After';p._props.DisplayName='Updated';w:Show()
        assert(w.UsernameLabel.Text=='@After' and w.DisplayNameLabel.Text=='Updated');finish(w)
    end)
    test('profile names are not translated and Unicode display names are preserved',function()
        local p=player('Settings','Ajuda');players.LocalPlayer=p;local w=fixture()
        w:SetLocale('en-US');assert(w.DisplayNameLabel.Text=='Ajuda' and w.UsernameLabel.Text=='@Settings')
        w:RegisterTranslations({name={Source='Ajuda',Values={['en-US']='Wrong identity'}}})
        assert(w.DisplayNameLabel.Text=='Ajuda');p.DisplayName='🦊 Gustavo';assert(w.DisplayNameLabel.Text=='🦊 Gustavo')
        finish(w)
    end)
    test('a real account named Player is accepted from the actual instance',function()
        players.LocalPlayer=player('Player','Player');local w=fixture()
        assert(w.DisplayNameLabel.Text=='Player' and w.UsernameLabel.Text=='@Player');finish(w)
    end)
    test('destroy and reexecution remove pending identity and avatar observers',function()
        players.LocalPlayer=nil;local old=fixture();old:Destroy()
        players.LocalPlayer=player('NewUser','New display');local w=fixture();Mock.pump()
        assert(w.DisplayNameLabel.Text=='New display' and old.Destroyed);finish(w)
    end)
    test('destroy during a yielding avatar request cannot affect the replacement window',function()
        Mock.YieldingTasks=true;players.LocalPlayer=player('Old','Old display',300)
        players.GetUserThumbnailAsync=function(_,id) task.wait(2);return 'avatar/'..id,true end
        local old=fixture();Mock.pump();assert(old.UsernameLabel.Text=='@Old')
        old.Gui:Destroy();assert(old.Destroyed and not old._profileState)
        players.LocalPlayer=player('Current','Current display',301);local w=fixture();Mock.pump();Mock.pump(3)
        assert(w.DisplayNameLabel.Text=='Current display' and w.Avatar.Image=='avatar/301')
        assert(not Library._thumbnails[300]);finish(w)
    end)
end
