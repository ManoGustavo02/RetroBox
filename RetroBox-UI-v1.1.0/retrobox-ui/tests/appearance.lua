return function(Mock,Library,test)
    local serial=0
    local function tick(dt)
        Mock.pump(dt or .5);Mock.Services.RunService.Heartbeat:Fire(dt or .1)
        Mock.Services.RunService.RenderStepped:Fire(dt or .1);Mock.pump(dt or .5)
    end
    local function fixture(options)
        serial=serial+1;Mock.AnimatedTweens=true;Mock.StrictIconLifecycle=true;Mock.Warnings={}
        Mock.ParentLockErrors=0;Mock.DestroyedIconWrites=0
        local settings={Id='appearance-'..serial,Theme='Hacker',Settings=false,FileStorage=false,LoadingScreen=false}
        for k,v in pairs(options or {}) do settings[k]=v end
        local w=Library:CreateWindow(settings);local t=w:CreateTab('Controls');local s=t:CreateSection('Controls');tick()
        return w,s,t
    end
    local function finish(w)
        w:Destroy();tick(100);Mock.AnimatedTweens=false;Mock.StrictIconLifecycle=false;Mock.DeferDestroying=false
        Mock.YieldingTasks=false;Mock.Geometry=false;Mock.Viewport=Vector2.new(1280,720)
        assert(Mock.Connections==0,'Appearance leaked connections: '..Mock.Connections)
        assert(Mock.ParentLockErrors==0 and Mock.DestroyedIconWrites==0,'Appearance wrote a destroyed icon')
        assert(#Mock.Warnings==0,table.concat(Mock.Warnings,'\n'))
    end
    local function hub(w,id,options)
        options=options or {};options.Id=id;options.LoadingScreen=false
        options.Games={{Id='game',Name='Game',Description='Description',PlaceId=123,Scripts={{Id='script',Title='Script',Callback=function() return true end}}}}
        return w:CreateScriptHub(options)
    end
    test('RGB text and color pickers share one bounded scheduler without changing text',function()
        local w,s=fixture();local c=s:AddLabel({Title='Olá, <texto>',Description='Descrição',RGB=true,DescriptionRGB={Speed=.5}})
        local picker=s:AddColorPicker({Default={Color='#FFFFFF',Rainbow=true}})
        local connection=w._rgbConnection;local old=c.TitleLabel.TextColor3;tick(.2)
        assert(c.TitleLabel.Text=='Olá, <texto>' and not c.TitleLabel.RichText)
        assert(c.TitleLabel.TextColor3~=old and w._rgbConnection==connection)
        assert(Library:ContrastRatio(c.TitleLabel.TextColor3,w:_surfaceColor(c.TitleLabel))>=4.499)
        c:SetRGB(false);c:SetRGB(false,'Description');assert(w._rgbConnection==connection)
        picker:SetRainbow(false);assert(not w._rgbConnection);finish(w)
    end)
    test('RGB replaces options in place and restores current themed colors',function()
        local w,s=fixture();local c=s:AddLabel({Title='Name',RGB=true,TitleRGB=false});assert(not (w._textRGB and w._textRGB[c.TitleLabel]));local e=w:SetRGB(c.TitleLabel,{Speed=.5})
        local again=w:SetRGB(c.TitleLabel,{Speed=1});assert(e==again and e:GetOptions().Speed==1)
        w:SetTheme('Paper');tick();e:Destroy();e:Destroy()
        assert(c.TitleLabel.TextColor3==w:_ink('Text',c.TitleLabel) and not w._rgbConnection)
        finish(w)
    end)
    test('RGB follows title subtitle value and description convenience methods',function()
        local w,s=fixture({TitleRGB=true,SubtitleRGB=true});local c=s:AddStatCard({Title='Total',Value=25,Description='Result'})
        c:SetRGB(true,'Value');c:SetRGB(true,'Description');assert(w._textRGB[c.ValueLabel] and w._textRGB[c.DescriptionLabel])
        w:SetTitleRGB(false);w:SetSubtitleRGB(false);c:SetRGB(false,'Value');c:SetRGB(false,'Description')
        assert(not next(w._textRGB) and not w._rgbConnection);finish(w)
    end)
    test('RGB sleeps with hidden tabs windows and controls and resumes on visibility',function()
        local w,s,t=fixture();local c=s:AddLabel({RGB=true});tick();assert(w._rgbConnection)
        c:SetVisible(false);assert(not w._rgbConnection);c:SetVisible(true);assert(w._rgbConnection)
        local second=w:CreateTab('Other');second:Select();assert(not w._rgbConnection)
        t:Select();assert(w._rgbConnection);w:Hide();assert(not w._rgbConnection)
        w:Show();assert(w._rgbConnection);w:Minimize(true);assert(not w._rgbConnection)
        w:Minimize(false);assert(w._rgbConnection);finish(w)
    end)
    test('RGB respects reduced motion disabled animations and intensity off',function()
        local w,s=fixture();local c=s:AddLabel({RGB=true});local e=w._textRGB[c.TitleLabel]
        w:SetReducedMotion(true);assert(not w._rgbConnection and c.TitleLabel.TextColor3==w:_ink('Text',c.TitleLabel))
        w:SetReducedMotion(false);assert(w._rgbConnection);w:SetAnimations({Enabled=false});assert(not w._rgbConnection)
        w:SetAnimations({Enabled=true,Intensity='Off'});assert(not w._rgbConnection)
        w:SetAnimations({Intensity='Subtle'});assert(w._rgbConnection)
        e:SetEnabled(false);assert(not w._rgbConnection);e:SetEnabled(true);assert(w._rgbConnection);finish(w)
    end)
    test('invalid RGB options targets and parts are rejected before creating effects',function()
        local w,s=fixture();local count=#s.Controls
        for _,options in ipairs({{Speed=0},{Contrast=99},{Enabled=1},{Oops=true},{Saturation=0/0}}) do
            assert(not pcall(function() s:AddLabel({Id='invalid-rgb',RGB=options}) end))
            assert(#s.Controls==count and not w.Controls['invalid-rgb'])
        end
        local c=s:AddLabel({});assert(not pcall(c.SetRGB,c,true,'Missing'))
        local other=Instance.new('TextLabel');other.Parent=Mock.CoreGui
        assert(not pcall(w.SetRGB,w,other,true));other:Destroy();finish(w)
    end)
    test('RGB releases detached and externally destroyed targets including deferred events',function()
        local w,s=fixture();local c=s:AddLabel({RGB=true});local e=w._textRGB[c.TitleLabel]
        c.TitleLabel.Parent=nil;assert(e.Destroyed and not w._rgbConnection);c.TitleLabel:Destroy();c:Destroy()
        local next=s:AddLabel({RGB=true});local handle=w._textRGB[next.TitleLabel]
        Mock.DeferDestroying=true;next.Frame:Destroy();Mock.pump();assert(handle.Destroyed and not handle.Target)
        finish(w)
    end)
    test('RGB count is bounded and all effects release on window destruction',function()
        local w,s=fixture();local controls={}
        for i=1,128 do controls[i]=s:AddLabel({Title=tostring(i),RGB=true}) end
        local before=#s.Controls;assert(not pcall(function() s:AddLabel({Id='over-limit-rgb',RGB=true}) end));assert(#s.Controls==before and not w.Controls['over-limit-rgb'])
        local last=s:AddLabel({Title='Limit'});assert(not pcall(w.SetRGB,w,last.TitleLabel,true))
        controls[1]:SetRGB(false);w:SetRGB(last.TitleLabel,true);assert(w._rgbConnection)
        finish(w)
    end)
    test('skeletons share the RGB scheduler and are static under reduced motion',function()
        local w,s=fixture();local c=s:AddSkeleton({Title='Loading',Lines=3});local f=c.Skeleton.Frame
        assert(w._rgbConnection and #c.Skeleton.Bars==3);local old=c.Skeleton.Bars[1].BackgroundTransparency
        tick(.2);assert(c.Skeleton.Bars[1].BackgroundTransparency~=old)
        c:SetLoading(false);assert(not f.Visible and not w._rgbConnection)
        c:SetLoading(true);w:SetReducedMotion(true);assert(f.Visible and not w._rgbConnection)
        c:Destroy();assert(not next(w._busyVisuals));finish(w)
    end)
    test('generic loading overlays preserve values and block callbacks until ready',function()
        local w,s=fixture();local calls=0;local c=s:AddButton({Title='Action',Callback=function() calls=calls+1 end})
        c:SetLoading(true);c.Button.Activated:Fire();tick();assert(calls==0 and c._loadingSkeleton)
        c:SetLoading(false);c.Button.Activated:Fire();tick();assert(calls==1 and not c._loadingSkeleton)
        local stat=s:AddStatCard({Value=10});stat:SetLoading(true);assert(stat.Loading and not stat._loadingSkeleton)
        stat:SetLoading(false);assert(stat:GetValue()==10);finish(w)
    end)
    test('small skeletons retain positive bounded bars and reject invalid parents before allocation',function()
        Mock.Geometry=true;local w,s=fixture();local c=s:AddSkeleton({Lines=8,Height=48})
        local root=c.Skeleton.Frame;local p,size=root.AbsolutePosition,root.AbsoluteSize
        for _,bar in ipairs(c.Skeleton.Bars) do
            local bp,bs=bar.AbsolutePosition,bar.AbsoluteSize
            assert(bs.Y>=0 and bp.Y>=p.Y-.1 and bp.Y+bs.Y<=p.Y+size.Y+.1)
        end
        local before=w:GetRuntimeStats().Resources;local folder=Instance.new('Folder');folder.Parent=w.Main
        assert(not pcall(w.CreateSkeleton,w,{Parent=folder}))
        assert(not pcall(w.CreateSkeleton,w,{Parent=s.Frame,Lines=false}))
        local count=#s.Controls;assert(not pcall(function() s:AddSkeleton({Id='invalid-skeleton',Lines=false}) end));assert(#s.Controls==count and not w.Controls['invalid-skeleton'])
        assert(not pcall(w.CreateSkeleton,w,{Parent=s.Frame,Size='bad'}))
        assert(w:GetRuntimeStats().Resources==before);folder:Destroy()
        local extra={};for i=1,127 do extra[i]=w:CreateSkeleton({Parent=s.Frame,Lines=1}) end
        local button=s:AddButton({});before=w:GetRuntimeStats().Resources;count=#s.Controls
        assert(not pcall(function() s:AddSkeleton({Id='over-limit-skeleton'}) end) and #s.Controls==count)
        assert(not pcall(button.SetLoading,button,true) and not button.Frame:GetAttribute('RetroBoxLoading'))
        assert(not pcall(w.ShowLoading,w,{}) and not w._loading and w:GetRuntimeStats().Resources==before)
        for _,effect in ipairs(extra) do effect:Destroy() end
        finish(w)
    end)
    test('loading screens have real progress finish idempotently and cancel replaced screens',function()
        local w,s=fixture();local c=s:AddButton({});local a=w:ShowLoading({Message='Real task'})
        assert(a.Progress==nil and not w:_interactionAllowed(c.Button))
        a:SetProgress(.4);tick();assert(a.Progress==.4 and a.Fill.Size.X.Scale==.4)
        assert(not pcall(a.SetProgress,a,2) and a.Progress==.4)
        local b=w:ShowLoading({Blocking=false});assert(a.Destroyed and w:_interactionAllowed(c.Button))
        b:Finish('Ready');b:Finish();b:SetProgress(.2);tick();assert(b.Destroyed and b.Progress==1 and not w._loading)
        b:Destroy();finish(w)
    end)
    test('loading timeout releases a stalled barrier without claiming task completion',function()
        local w=fixture();local loading=w:ShowLoading({Timeout=1});loading:SetProgress(.25)
        Mock.pump(1.1);assert(loading.Destroyed and loading.Progress==.25 and not w._loading)
        finish(w)
    end)
    test('automatic startup is optional nonblocking and has no minimum artificial delay',function()
        local w=fixture({LoadingScreen=true});tick();assert(not w._loading)
        local second=Library:CreateWindow({Id='startup-test',Settings=false,FileStorage=false})
        assert(second._loading and second._loading.Blocking==false)
        second:Destroy();tick();assert(not second._loading)
        finish(w)
    end)
    test('loading card and skeleton fit a small scaled viewport',function()
        Mock.Geometry=true;Mock.Viewport=Vector2.new(360,640)
        local w=fixture({Size=Vector2.new(300,360),Scale=.75});local loading=w:ShowLoading({})
        for _,bar in ipairs(loading.Skeleton.Bars) do assert(bar.Size.Y.Offset>-30 and bar.AbsoluteSize.Y>=0) end
        local p,size=loading.Frame.AbsolutePosition,loading.Frame.AbsoluteSize
        local card=loading.TitleLabel.Parent;local cp,cs=card.AbsolutePosition,card.AbsoluteSize
        assert(cp.X>=p.X and cp.X+cs.X<=p.X+size.X+.1 and cp.Y>=p.Y and cp.Y+cs.Y<=p.Y+size.Y+.1)
        finish(w)
    end)
    test('hub profiles own a separate palette and do not change the window or sibling hubs',function()
        local w=fixture();local a=hub(w,'a');local b=hub(w,'b',{HubTheme='Paper'});tick()
        assert(a:GetThemeProfile().Theme=='Launcher' and w.Theme=='Hacker')
        local original=Library.HubThemes.Launcher.Accent;a:SetAccent('#E78AFF')
        assert(a.HubPalette.Accent==Color3.fromRGB(231,138,255) and Library.HubThemes.Launcher.Accent==original)
        assert(b.HubPalette.Background==Library.Themes.Paper.Background and w.Palette.Background==Library.Themes.Hacker.Background)
        assert(a.Launcher.UI.Background.BackgroundColor3==a.HubPalette.Background)
        w:SetTheme('Nord');assert(a.Launcher.UI.Background.BackgroundColor3==a.HubPalette.Background)
        a.GameSearch.Input:CaptureFocus();tick();assert(a.GameSearch.Input.BorderColor3==a.HubPalette.Accent)
        a.GameSearch.Input:ReleaseFocus();finish(w)
    end)
    test('hub button hover and pixel icon roles use the local palette',function()
        local w=fixture();local h=hub(w,'local',{HubTheme='Paper'});tick()
        h.PlayButton.Button.MouseEnter:Fire();tick()
        assert(h.PlayButton.Button.BackgroundColor3==h.HubPalette.Highlight)
        local icon=h.Launcher.UI.Appearance._titleIcon
        assert(icon and icon.Frame and #icon.Nodes>0)
        for _,node in ipairs(icon.Foreground) do assert(node.BackgroundColor3==h.HubPalette.Text) end
        finish(w)
    end)
    test('hub theme profiles persist atomically and malformed imports leave colors and flags unchanged',function()
        local w,s=fixture();local c=s:AddToggle({Id='keep',Default=true});local h=hub(w,'saved');h:SetThemeProfile({Theme='Launcher',Colors={Surface='#183042'},Accent='#55DDEE'})
        local profile=w:ExportConfig(true);h:SetTheme('Paper');assert(w:ImportConfig(profile,{Silent=true}));tick()
        assert(h:GetThemeProfile().Accent=='#55DDEE' and h.HubPalette.Surface==Color3.fromRGB(24,48,66) and c:GetValue())
        local original=h.HubPalette.Accent;profile.Appearance.Advanced.HubThemes.saved.Colors.Missing='#000000';profile.Flags.keep.Value=false
        assert(not w:ImportConfig(profile,{Silent=true}) and c:GetValue() and h.HubPalette.Accent==original)
        h:ResetThemeProfile();assert(h:GetThemeProfile().Theme=='Launcher' and not h:GetThemeProfile().Accent)
        finish(w)
    end)
    test('hub profile import supports a hub created later and a custom theme in the same transaction',function()
        local w=fixture();w:CreateTheme('PolishCustom','Ocean');local profile=w:ExportConfig(true)
        profile.Appearance.Advanced.HubThemes={later={Theme='PolishCustom',Accent='#ABCDEF'}}
        assert(w:ImportConfig(profile,{Silent=true}));local h=hub(w,'later')
        assert(h:GetThemeProfile().Theme=='PolishCustom' and h.HubPalette.Accent==Color3.fromRGB(171,205,239));finish(w)
    end)
    test('hub appearance editor can close reopen customize and restore without leaking',function()
        local w=fixture();local h=hub(w,'editor');tick();local baseline=w:GetRuntimeStats().Resources
        for _=1,3 do
            local tab=h:ShowThemeSettings();h._themePickers.Accent:SetColor('#FA88CC');tick()
            assert(h.HubPalette.Accent==Color3.fromRGB(250,136,204));tab:Destroy();tick();assert(not h._themeTab)
        end
        assert(w:GetRuntimeStats().Resources==baseline,'Theme editor retained owned resources')
        h:ShowThemeSettings();h:Destroy();tick();assert(not h._themeTab and not next(w._paletteScopes));finish(w)
    end)
    test('hub RGB uses explicit roles and keeps profile and catalog identity intact',function()
        local w=fixture();local h=hub(w,'rgb',{HubTitleRGB=true,HubDescriptionRGB={Speed=.4}});h.Tab:Select();tick()
        local before=h:GetGames();h:SetRGB(true,'SelectedScript');assert(w._textRGB[h.Launcher.UI.SelectedScript])
        h:SetTheme('Paper');assert(h:GetGames()[1].Id==before[1].Id and h:GetSelectedScript().Id=='script')
        h:SetRGB(false);h:SetRGB(false,'Description');h:SetRGB(false,'SelectedScript');assert(not next(w._textRGB));finish(w)
    end)
    test('hub menus and tooltips inherit local colors and follow profile changes',function()
        local w=fixture();local h=hub(w,'overlays',{HubTheme='Paper'});tick()
        h.Sort:SetOpen(true);tick();local menu=assert(w._overlay)
        assert(menu.Panels[1].Frame.BackgroundColor3==h.HubPalette.Surface)
        h:SetTheme('Ocean');assert(menu.Panels[1].Frame.BackgroundColor3==h.HubPalette.Surface)
        menu:Close();h.PlayButton:SetTooltip('Details');h.PlayButton:ShowTooltip();tick()
        assert(w.TooltipFrame.Visible and w.TooltipFrame.BackgroundColor3==h.HubPalette.Surface)
        h:SetTheme('Paper');assert(w.TooltipFrame.BackgroundColor3==h.HubPalette.Surface)
        finish(w)
    end)
    test('a hub profile retains its own colors after a source custom theme is deleted',function()
        local w=fixture();w:CreateTheme('PolishSource','Ocean');local h=hub(w,'snapshot',{HubTheme='PolishSource'});tick()
        local color=h.HubPalette.Background;w:DeleteTheme('PolishSource')
        local profile=w:ExportConfig(true);assert(w:ImportConfig(profile,{Silent=true}));tick()
        assert(h.HubPalette.Background==color and h:GetThemeProfile().Theme=='PolishSource')
        h:ShowThemeSettings();h:ResetThemeProfile();assert(h.HubPalette.Background==color);finish(w)
    end)
    test('ordinary pages reveal their text without changing values callbacks or disabled motion',function()
        local w,s,t=fixture();local n=0;local c=s:AddToggle({Title='Value',Description='Detail',Callback=function() n=n+1 end})
        local second=w:CreateTab('Other');second:Select();tick();t:Select()
        assert(w._tweens[c.TitleLabel] and not c:GetValue() and n==0);tick()
        w:SetReducedMotion(true);second:Select();t:Select();assert(not w._tweens[c.TitleLabel] and c.TitleLabel.TextTransparency==0)
        finish(w)
    end)
    test('hub loading placeholders follow metadata success failure and universal selection',function()
        local w=fixture();Mock.YieldingTasks=true
        local h=w:CreateScriptHub({Id='metadata-effects',LoadingScreen=false,Games={{Id='auto',PlaceId=891,Scripts={}}},
            UniversalScripts={{Id='u',Name='Universal',URL='https://pastefy.app/example/raw'}},
            GameMetadata={Provider=function() task.wait(1);return {Name='Resolved',Description='Ready'} end}})
        Mock.pump();h.Launcher:Refresh();assert(h.Launcher.MetadataSkeleton.Frame.Visible)
        Mock.pump(2);h.Launcher:Refresh();assert(not h.Launcher.MetadataSkeleton.Frame.Visible and h.Launcher.UI.GameTitle.Text=='Resolved')
        h:SelectUniversalScripts();tick();assert(not h.Launcher.MetadataSkeleton.Frame.Visible and not h.Launcher.CoverSkeleton.Frame.Visible)
        finish(w)
    end)
    test('window and hub reexecution destroy every new effect and old profile observers',function()
        local w,s=fixture({Id='reexecute-polish',TitleRGB=true});s:AddSkeleton({});s:AddLabel({RGB=true});local h=hub(w,'old');h:ShowThemeSettings();w:ShowLoading({})
        Mock.DeferDestroying=true
        local second=Library:CreateWindow({Id='reexecute-polish',Settings=false,FileStorage=false,LoadingScreen=false})
        tick();assert(w.Destroyed and h.Destroyed and not next(w._textRGB) and not next(w._busyVisuals))
        second:Destroy();finish(w)
    end)
