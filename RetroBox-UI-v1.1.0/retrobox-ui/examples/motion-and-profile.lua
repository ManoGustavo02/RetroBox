-- Native executor showcase: all numbers are synthetic demonstration data.
local Library=loadstring(game:HttpGet('https://raw.githubusercontent.com/ManoGustavo02/RetroBox/main/dist/bootstrap/v2.lua'))({Channel='stable',MinVersion='2.6.0'})
local window=Library:CreateWindow({Id='motion-and-profile',Title='RetroBox · movimento',Theme='Hacker',Size=Vector2.new(980,720)})
local page=window:CreateTab({Title='Dados de demonstração',Icon='grid'})
local section=page:CreateSection('Movimento e dados')
local total=section:AddStatCard({Title='Pontos fictícios',Value=120,Format='Compact',Unit='pts',Sparkline=true,Icon='diamond'})
local chart=section:AddLineChart({Title='Histórico fictício',Data={3,6,4,8,5},MaxPoints=20})
local bars=section:AddBarChart({Title='Barras de demonstração',Data={4,7,5,2},Min=0,Max=10})
local progress=section:AddProgressChart({Title='Progresso de demonstração',Value=20})
section:AddButton({Title='Atualizar a demonstração',Icon='refresh',Callback=function()
    total:SetValue(total:GetValue()+35);total:AddPoint(total:GetValue())
    chart:AddPoint(math.random(1,10));bars:SetData({math.random(1,10),math.random(1,10),math.random(1,10),math.random(1,10)})
    progress:SetValue((progress:GetValue()+17)%101)
end})
local controls=window:CreateTab({Title='Interações',Icon='settings'}):CreateSection({Title='Controles',Collapsible=true})
controls:AddToggle({Title='Exemplo com tecla e ajuda',Keybind=Enum.KeyCode.F6,Tooltip='A tecla e a ajuda mantêm suas próprias áreas clicáveis.',Default=false})
controls:AddSlider({Title='Valor de demonstração',Min=0,Max=100,Default=30})
controls:AddInput({Title='Campo com foco',Placeholder='Digite um texto de teste'})
controls:AddDropdown({Title='Escolha',Options={'Opção A','Opção B','Opção C'}})
controls:AddColorPicker({Title='Cor de demonstração',Default='#2ee96b'})
controls:AddLabel({Title='O rodapé usa o jogador real desta sessão.',Description='A engrenagem permite mudar velocidade, intensidade e movimento reduzido. Nenhum código de gameplay é executado.'})
return window
